#!/usr/bin/env bash
#
# install-reinstall.test.sh — Keycloak 24 integration test: a re-run of
# install-cloud.sh applies rotated Keycloak values (WP-386, INS-05, F-125).
# Needs Docker (quay.io/keycloak/keycloak:24.0, postgres:16-alpine).
#
# Runs the Keycloak steps of the installer — collect_config, write_env,
# configure_realm and the Keycloak part of start_stack (keycloak-db and
# keycloak up and healthy, validate_keycloak_bootstrap, create_initial_admin)
# — against keycloak-db and keycloak of deploy/docker-compose/docker-compose.yml
# in a throwaway compose project:
#   1. first run with values A (secrets generated by the installer);
#   2. KEYCLOAK_ADMIN_PASSWORD, RETICORA_OIDC_CLIENT_SECRET and
#      RETICORA_OIDC_REDIRECT_URL rotated in .env, second run: kcadm login
#      with the new password rc 0, with the old one rc != 0; client secret =
#      .env; redirectUris contain the new URL; client_credentials token with
#      the new secret 200, with the old one 401; each rotation logged once,
#      without its value;
#   3. third run without a change: no kcadm write call, no rotation logged.
# Before the runs it checks the order of start_stack: the Keycloak steps
# above, and the server stop and TimescaleDB update between sync_db_password
# and run_migrations (WP-604).
# The realm ships reticora-app without a service account; for the
# client_credentials check the test enables it after the first run. The
# installer leaves that setting alone (only secret, redirect URIs and web
# origins are applied).
#
# Usage: ./tests/install-reinstall.test.sh
#   RETICORA_REINSTALL_KC_PORT  host port of the test Keycloak (default 18180)
set -uo pipefail

cd "$(dirname "$0")/.." || exit 1
REPO_ROOT="$(pwd)"

if ! docker info >/dev/null 2>&1 || ! command -v jq >/dev/null; then
    echo "FAIL: Docker and jq are required"
    exit 1
fi

TMP_ROOT="$(mktemp -d)"
PROJECT="reticora-reinstall-$$"
KC_PORT="${RETICORA_REINSTALL_KC_PORT:-18180}"
T_COMPOSE_DIR="$TMP_ROOT/compose"
T_ENV="$T_COMPOSE_DIR/.env"
KCADM_CALLS="$TMP_ROOT/kcadm-calls"
mkdir -p "$T_COMPOSE_DIR"
# A copy, so that the realm file lands in the throwaway .generated/.
cp deploy/docker-compose/docker-compose.yml "$T_COMPOSE_DIR/"

compose() { docker compose -p "$PROJECT" --env-file "$T_ENV" -f "$T_COMPOSE_DIR/docker-compose.yml" "$@"; }

cleanup() {
    [ ! -f "$T_ENV" ] || compose down -v --remove-orphans >/dev/null 2>&1
    rm -rf "$TMP_ROOT"
}
trap cleanup EXIT

HARNESS="$TMP_ROOT/harness.sh"
head -n -1 install-cloud.sh > "$HARNESS"
cp install-preflight.sh "$TMP_ROOT/"

PASS=0
FAIL=0
ok()    { PASS=$((PASS + 1)); printf 'ok   %s\n' "$1"; }
fail()  { FAIL=$((FAIL + 1)); printf 'FAIL %s\n' "$1"; }
check() { local name="$1"; shift; if "$@"; then ok "$name"; else fail "$name"; fi; }

env_value() { sed -n "s/^$1=//p" "$T_ENV" | tail -n 1; }

# installer_run <log> — one installer run, restricted to its Keycloak steps,
# in a fresh shell with install-cloud.sh loaded (main stripped). Every kcadm
# call is recorded in KCADM_CALLS by its first two arguments (never a secret).
# shellcheck disable=SC2034,SC2317 # settings and the wrapper used by the installer
installer_run() {
    (
        set --
        # shellcheck disable=SC1090
        . "$HARNESS"
        NON_INTERACTIVE=1
        SCRIPT_DIR="$REPO_ROOT"
        COMPOSE_DIR="$T_COMPOSE_DIR"
        COMPOSE_FILE="$COMPOSE_DIR/docker-compose.yml"
        OVERRIDE_FILE="$COMPOSE_DIR/docker-compose.override.yml"
        ENV_FILE="$T_ENV"
        COMPOSE=(docker compose -p "$PROJECT")
        eval "installer_$(declare -f kcadm)"
        kcadm() { printf '%s %s\n' "$1" "$2" >> "$KCADM_CALLS"; installer_kcadm "$@"; }
        collect_config
        write_env
        configure_realm
        compose_cmd up -d keycloak-db
        wait_for_service keycloak-db || die "keycloak-db did not become healthy."
        compose_cmd up -d keycloak
        wait_for_service keycloak || { show_service_logs keycloak; die "Keycloak did not become healthy."; }
        validate_keycloak_bootstrap
        create_initial_admin
    ) > "$1" 2>&1
}

# start_stack_order <step>... — the steps occur in start_stack in this order.
start_stack_order() {
    local body prev=0 n step
    # shellcheck disable=SC1090
    body="$(set --; . "$HARNESS" >/dev/null 2>&1; declare -f start_stack)"
    for step in "$@"; do
        n="$(printf '%s\n' "$body" | grep -n -F -- "$step" | head -n 1 | cut -d: -f1)"
        [ -n "$n" ] && [ "$n" -gt "$prev" ] || return 1
        prev="$n"
    done
}

# The steps above are those of start_stack, in its order.
mirrors_start_stack() {
    start_stack_order 'up -d postgres nats redis minio keycloak-db' 'wait_for_service keycloak-db' 'up -d keycloak' \
        'wait_for_service keycloak ' 'validate_keycloak_bootstrap' 'create_initial_admin'
}

# A re-run on a newer database image (WP-604): after the password sync the
# server is stopped and the TimescaleDB extension updated
# (scripts/ops/timescaledb-update.sh, tests/timescaledb-update.test.sh),
# before the migrations.
updates_timescaledb_before_migrations() {
    start_stack_order 'sync_db_password' 'compose_cmd stop server' 'update_timescaledb' 'run_migrations'
}

# Admin CLI of the test itself (own config file inside the container).
kc() { compose exec -T keycloak /opt/keycloak/bin/kcadm.sh "$@" --config /tmp/reinstall-test.config; }
kc_login() {
    kc config credentials --server http://localhost:8080 --realm master --user admin --password "$1" >/dev/null 2>&1
}
client_uuid() { kc get clients -r reticora -q clientId=reticora-app --fields id --format csv --noquotes 2>/dev/null | head -n 1; }
token_status() {
    curl -s -o /dev/null -w '%{http_code}' --max-time 10 \
        -d grant_type=client_credentials -d client_id=reticora-app --data-urlencode "client_secret=$1" \
        "http://localhost:${KC_PORT}/realms/reticora/protocol/openid-connect/token"
}
kc_writes() { grep -cE '^(create|update|delete|set-password|add-roles|remove-roles) ' "$KCADM_CALLS"; }
no_secret_in_log() {
    local s
    for s in "$A_ADMIN" "$B_ADMIN" "$A_SECRET" "$B_SECRET"; do
        ! grep -q -F -- "$s" "$LOG" || return 1
    done
}

old_admin_refused() { ! kc_login "$A_ADMIN"; }
client_secret_is_env() {
    [ "$(kc get "clients/$UUID/client-secret" -r reticora 2>/dev/null | jq -r .value)" = "$(env_value RETICORA_OIDC_CLIENT_SECRET)" ]
}
client_has() { kc get "clients/$UUID" -r reticora 2>/dev/null | jq -e --arg v "$2" ".$1 | index(\$v)" >/dev/null; }
client_untouched() {
    kc get "clients/$UUID" -r reticora 2>/dev/null |
        jq -e '.serviceAccountsEnabled == true and .publicClient == false and .directAccessGrantsEnabled == true' >/dev/null
}
one_write_per_rotated_value() {
    [ "$(grep -c '^update users/[^ ]*/reset-password$' "$KCADM_CALLS")" -eq 1 ] &&
        [ "$(grep -c '^update clients/' "$KCADM_CALLS")" -eq 3 ] && [ "$(kc_writes)" -eq 4 ]
}
rotations_logged() {
    [ "$(grep -c 'Keycloak rotation:' "$LOG")" -eq 4 ] &&
        grep -q 'Changed since the last run: KEYCLOAK_ADMIN_PASSWORD RETICORA_OIDC_CLIENT_SECRET RETICORA_OIDC_REDIRECT_URL' "$LOG" &&
        no_secret_in_log
}
previous_env_applied() {
    [ "$(stat -c %a "$T_ENV.previous")" = 600 ] && grep -qx "KEYCLOAK_ADMIN_PASSWORD=$B_ADMIN" "$T_ENV.previous"
}
no_rotation_logged() { ! grep -q -e 'Keycloak rotation:' -e 'Changed since the last run' "$LOG"; }

check "the test runs the Keycloak steps of start_stack in its order" mirrors_start_stack
check "start_stack stops the server and updates TimescaleDB between sync_db_password and run_migrations" \
    updates_timescaledb_before_migrations

# ─── 1. first run with values A ──────────────────────────────────────────────
cat > "$T_ENV" <<ENV
RETICORA_PUBLIC_BASE_URL=http://192.0.2.10:3000
RETICORA_OIDC_ISSUER_URL=http://192.0.2.10:${KC_PORT}/realms/reticora
RETICORA_OIDC_REDIRECT_URL=http://192.0.2.10:3000/auth/callback
RETICORA_KEYCLOAK_PORT=${KC_PORT}
ENV
LOG="$TMP_ROOT/run1.log"
: > "$KCADM_CALLS"
if ! installer_run "$LOG"; then
    fail "first run with values A"
    tail -n 40 "$LOG"
    printf '%d passed, %d failed\n' "$PASS" "$FAIL"
    exit 1
fi
ok "first run with values A"
A_ADMIN="$(env_value KEYCLOAK_ADMIN_PASSWORD)"
A_SECRET="$(env_value RETICORA_OIDC_CLIENT_SECRET)"
check "first run: kcadm login with the admin password A" kc_login "$A_ADMIN"
check "first run: the initial administrator was created" grep -q 'Initial administrator admin@reticora.example created' "$LOG"
check "first run: no rotation logged" no_rotation_logged
UUID="$(client_uuid)"
kc update "clients/$UUID" -r reticora -s serviceAccountsEnabled=true >/dev/null 2>&1
check "first run: client_credentials with secret A 200" [ "$(token_status "$A_SECRET")" = 200 ]

# ─── 2. rotate in .env, second run ───────────────────────────────────────────
B_ADMIN="$(openssl rand -hex 16)"
B_SECRET="$(openssl rand -hex 24)"
B_REDIRECT="http://cmdb-b.example.test:3000/auth/callback"
sed -i -e "s|^KEYCLOAK_ADMIN_PASSWORD=.*|KEYCLOAK_ADMIN_PASSWORD=$B_ADMIN|" \
    -e "s|^RETICORA_OIDC_CLIENT_SECRET=.*|RETICORA_OIDC_CLIENT_SECRET=$B_SECRET|" \
    -e "s|^RETICORA_OIDC_REDIRECT_URL=.*|RETICORA_OIDC_REDIRECT_URL=$B_REDIRECT|" "$T_ENV"
LOG="$TMP_ROOT/run2.log"
: > "$KCADM_CALLS"
if installer_run "$LOG"; then ok "second run with rotated values rc 0"; else fail "second run with rotated values rc 0"; tail -n 20 "$LOG"; fi
check "second run: kcadm login with the new admin password rc 0" kc_login "$B_ADMIN"
check "second run: kcadm login with the old admin password rc != 0" old_admin_refused
kc_login "$B_ADMIN"
check "second run: client secret = RETICORA_OIDC_CLIENT_SECRET of .env" client_secret_is_env
check "second run: redirectUris contain the new redirect URL" client_has redirectUris "$B_REDIRECT"
check "second run: webOrigins contain the new origin" client_has webOrigins "http://cmdb-b.example.test:3000"
check "second run: settings other than secret, redirect URIs, web origins kept" client_untouched
check "second run: client_credentials with the new secret 200" [ "$(token_status "$B_SECRET")" = 200 ]
check "second run: client_credentials with the old secret 401" [ "$(token_status "$A_SECRET")" = 401 ]
check "second run: one admin password reset and one client update per rotated value" one_write_per_rotated_value
check "second run: each rotation logged once, without its value" rotations_logged
check "second run: .env.previous (0600) holds the applied values" previous_env_applied

# ─── 3. third run without a change ───────────────────────────────────────────
LOG="$TMP_ROOT/run3.log"
: > "$KCADM_CALLS"
if installer_run "$LOG"; then ok "third run without a change rc 0"; else fail "third run without a change rc 0"; tail -n 20 "$LOG"; fi
check "third run: no kcadm write call" [ "$(kc_writes)" -eq 0 ]
check "third run: no rotation logged" no_rotation_logged
check "third run: the new admin password still works" kc_login "$B_ADMIN"
check "third run: client_credentials with the new secret 200" [ "$(token_status "$B_SECRET")" = 200 ]

echo
printf '%d passed, %d failed\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
