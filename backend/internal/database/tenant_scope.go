// Session variables (GUCs) WithTenant sets transaction-locally for the RLS
// policies (TEN-04). The names follow the TEN-04 text; package
// tenant/rls uses the same names for the RLS catalog test.
const (
	OrgGUC         = "app.org_id"
	UserGUC        = "app.user_id"
	ClientScopeGUC = "app.client_scope"
	SiteScopeGUC   = "app.site_scope"
	TeamScopeGUC   = "app.team_scope"
)

// OrgWideScopeSQL is the SQL condition "the transaction is not restricted in
// the client or site scope" (both GUCs empty, as WithTenant sets them for
// AllScopes). Repositories use it where only org-wide principals may write
// (E-09), in line with the policies of migration 000139.
const OrgWideScopeSQL = "(NULLIF(current_setting('" + ClientScopeGUC + "', true), '') IS NULL" +
	" AND NULLIF(current_setting('" + SiteScopeGUC + "', true), '') IS NULL)"

// ScopedWriteSQL is the SQL condition "client_id and site_id of the row are
// in the transaction's write scope" (unqualified columns, resolved in the
// innermost FROM): an org-wide principal writes every row, a scoped principal
// only rows of its clients and sites and no org-wide one (NULL, E-09), like
// the WITH CHECK of the link tables of migration 000064. Repositories count
// the writable links with it (migration 000146).
const ScopedWriteSQL = "((NULLIF(current_setting('" + ClientScopeGUC + "', true), '') IS NULL" +
	" OR client_id = ANY (string_to_array(current_setting('" + ClientScopeGUC + "', true), ',')::uuid[]))" +
	" AND (NULLIF(current_setting('" + SiteScopeGUC + "', true), '') IS NULL" +
	" OR site_id = ANY (string_to_array(current_setting('" + SiteScopeGUC + "', true), ',')::uuid[])))"

// noAccessScope is the GUC value of an empty scope set. The policies treat an
// unset or empty scope GUC as "all" (TEN-04: NULL = all clients of the org),
// so an empty set is encoded as the nil UUID, which matches no row: the
// referenced ids are generated by gen_random_uuid() (E-08, fail-closed).
const noAccessScope = "00000000-0000-0000-0000-000000000000"

// ErrIncompleteScope is returned by TenantScope.Validate when the organization
// is missing or a scope dimension was never decided. The zero value of
// TenantScope is always incomplete, so a forgotten scope fails closed.
var ErrIncompleteScope = errors.New("tenant scope is incomplete")

// ScopeSet is one scope dimension (clients, sites or teams) of a TenantScope.
// Its zero value is undecided and rejected by Validate. AllScopes grants the
// whole organization; ScopeIDs restricts to the given ids, and an empty list
// grants nothing (E-08).
type ScopeSet struct {
	decided bool
	all     bool
	ids     []string
}

// AllScopes returns the explicit org-wide marker of a scope dimension: the GUC
// stays empty, which the policies read as NULL = all rows of the organization.
func AllScopes() ScopeSet {
	return ScopeSet{decided: true, all: true}
}

// ScopeIDs restricts a scope dimension to the given ids. Without ids the
// dimension grants no access.
func ScopeIDs(ids ...string) ScopeSet {
	return ScopeSet{decided: true, ids: append([]string(nil), ids...)}
}

// IsAll reports whether the set is the org-wide marker.
func (s ScopeSet) IsAll() bool { return s.all }

// IDs returns a copy of the restricted ids; nil for the org-wide marker.
func (s ScopeSet) IDs() []string { return append([]string(nil), s.ids...) }

func (s ScopeSet) validate(name string) error {
	if !s.decided {
		return fmt.Errorf("%w: %s scope is not set (use AllScopes or ScopeIDs)", ErrIncompleteScope, name)
	}
	for _, id := range s.ids {
		if !isUUID(id) {
			return fmt.Errorf("invalid %s scope id %q: not a UUID", name, id)
		}
	}
	return nil
}

// gucValue renders the set for its GUC. The policies parse the value with
// string_to_array(…, ',')::uuid[] (migration 000033), so the uuid[] of TEN-04
// is transported as a comma-separated list.
func (s ScopeSet) gucValue() string {
	switch {
	case s.all:
		return ""
	case len(s.ids) == 0:
		return noAccessScope
	}
	ids := make([]string, len(s.ids))
	for i, id := range s.ids {
		ids[i] = strings.ToLower(id)
	}
	return strings.Join(ids, ",")
}

// TenantScope is the complete RLS context of one transaction (TEN-04): the
// organization, the acting user and the client, site and team scope.
type TenantScope struct {
	OrgID string
	// UserID is the acting user; empty for system jobs.
	UserID  string
	Clients ScopeSet
	Sites   ScopeSet
	Teams   ScopeSet
}

// OrgWideScope returns the scope of an org-wide principal or of a system job
// iterating one tenant (TEN-06: scopes NULL).
func OrgWideScope(orgID, userID string) TenantScope {
	return TenantScope{
		OrgID:   orgID,
		UserID:  userID,
		Clients: AllScopes(),
		Sites:   AllScopes(),
		Teams:   AllScopes(),
	}
}

// Validate checks that the scope is complete: a valid organization id and a
// decision for every scope dimension. A nil scope is incomplete. The user id
// is free text, but WithTenant writes it into the statement that opens the
// transaction, so a NUL byte or invalid UTF-8 is refused.
func (s *TenantScope) Validate() error {
	if s == nil || s.OrgID == "" {
		return fmt.Errorf("%w: organization id is required", ErrIncompleteScope)
	}
	if !isUUID(s.OrgID) {
		return fmt.Errorf("invalid organization id %q: not a UUID", s.OrgID)
	}
	if strings.IndexByte(s.UserID, 0) >= 0 || !utf8.ValidString(s.UserID) {
		return fmt.Errorf("invalid user id %q: NUL byte or invalid UTF-8", s.UserID)
	}
	if err := s.Clients.validate("client"); err != nil {
		return err
	}
	if err := s.Sites.validate("site"); err != nil {
		return err
	}
	return s.Teams.validate("team")
}

// isUUID accepts exactly the canonical 8-4-4-4-12 hex form that the policies
// cast with ::uuid.
func isUUID(s string) bool {
	if len(s) != 36 {
		return false
	}
	for i, r := range s {
		switch i {
		case 8, 13, 18, 23:
			if r != '-' {
				return false
			}
		default:
			if (r < '0' || r > '9') && (r < 'a' || r > 'f') && (r < 'A' || r > 'F') {
				return false
			}
		}
	}
	return true
}

type tenantScopeKey struct{}

// ContextWithTenantScope attaches the request's tenant scope; the tenant
// middleware sets it from the authenticated principal.
func ContextWithTenantScope(ctx context.Context, s *TenantScope) context.Context {
	return context.WithValue(ctx, tenantScopeKey{}, *s)
}

// TenantScopeFromContext returns the scope attached by ContextWithTenantScope.
func TenantScopeFromContext(ctx context.Context) (TenantScope, bool) {
	s, ok := ctx.Value(tenantScopeKey{}).(TenantScope)
	return s, ok
}

// ErrNoTenantScope is returned by WithRequestTenant when the context carries
// no tenant scope. A repository call outside a request or a system context
// therefore fails closed instead of running org-wide (E-08).
var ErrNoTenantScope = errors.New("no tenant scope in context")

// ErrTenantMismatch is returned by WithRequestTenant when the organization of
// a call differs from the organization of the context's scope.
var ErrTenantMismatch = errors.New("organization does not match the tenant scope")

// WithRequestTenant runs fn through WithTenant with the scope attached to ctx
// (ContextWithTenantScope). Repositories that receive the organization as an
// argument use it so the transaction carries the principal's complete scope;
// orgID must be the scope's organization. A transaction in ctx
// (ContextWithTx) is joined.
func WithRequestTenant(ctx context.Context, pool *pgxpool.Pool, orgID string, fn func(ctx context.Context, tx pgx.Tx) error) error {
	scope, ok := TenantScopeFromContext(ctx)
	if !ok {
		return ErrNoTenantScope
	}
	if !strings.EqualFold(scope.OrgID, orgID) {
		return fmt.Errorf("%w: %q", ErrTenantMismatch, orgID)
	}
	return WithTenant(ctx, pool, &scope, fn)
}

// Joining a transaction (NFR-03): a caller that runs several repository calls
// as one unit carries its transaction in the context (ContextWithTx,
// WithRequestTenantTx). WithTenant and WithRequestTenant called with that
// context run fn in it instead of opening their own transaction, so the
// repositories stay unchanged. Only the owner commits or rolls back.

var (
	// ErrTxNotJoinable is returned when the context carries a transaction
	// that WithTenant did not open, e.g. a WithSystem transaction.
	ErrTxNotJoinable = errors.New("the context transaction cannot be joined")
	// ErrTxScopeMismatch is returned when the scope of a call differs from
	// the scope of the context transaction: the call would run under the
	// other scope's GUCs, and a second transaction of the same goroutine
	// could wait forever for the organization's advisory locks the first
	// one holds.
	ErrTxScopeMismatch = errors.New("tenant scope differs from the scope of the context transaction")
	// ErrTxDone is returned when the context outlived its transaction.
	ErrTxDone = errors.New("the context transaction has ended")
	// ErrTxAborted is returned instead of a commit when a statement of the
	// transaction failed and nobody returned its error.
	ErrTxAborted = errors.New("transaction aborted by a failed statement")
)

type txKey struct{}

// States of a tenantTx.
const (
	txOpen int32 = iota
	txCommitted
	txRolledBack
)

// tenantTx is the transaction WithTenant hands to fn: the pgx transaction,
// the scope its GUCs were set from and the callbacks waiting for the commit.
type tenantTx struct {
	pgx.Tx
	scope TenantScope
	state atomic.Int32
	mu    sync.Mutex
	after []func(context.Context)
	// before are the writes BeforeCommit put last.
	before []func() error
}

// aborted reports whether a statement failed in the open transaction; it
// reads the connection's transaction status without a round trip.
func (t *tenantTx) aborted() bool {
	return t.state.Load() == txOpen && t.Conn().PgConn().TxStatus() == 'E'
}

// runBeforeCommit runs the writes registered with BeforeCommit in order,
// including those registered while they run, and stops at the first error.
func (t *tenantTx) runBeforeCommit() error {
	for i := 0; ; i++ {
		t.mu.Lock()
		if i >= len(t.before) {
			t.before = nil
			t.mu.Unlock()
			return nil
		}
		fn := t.before[i]
		t.mu.Unlock()
		if err := fn(); err != nil {
			return err
		}
	}
}

// runAfterCommit runs the callbacks registered with AfterCommit in order,
// each with ctx; a panicking callback is logged, the others still run.
func (t *tenantTx) runAfterCommit(ctx context.Context) {
	t.mu.Lock()
	callbacks := t.after
	t.after = nil
	t.mu.Unlock()
	for _, fn := range callbacks {
		func() {
			defer func() {
				if r := recover(); r != nil {
					slog.ErrorContext(ctx, "after-commit callback failed", "panic", r)
				}
			}()
			fn(ctx)
		}()
	}
}

// ContextWithTx returns ctx carrying tx: WithTenant and WithRequestTenant
// called with it join tx (no BEGIN, no set_config, no COMMIT) when their
// scope is the scope of tx, and fail with ErrTxScopeMismatch otherwise. A
// context without a tenant scope takes the scope of tx; a context with a
// scope keeps it, so a scope that differs from the transaction's is never
// widened to it: its joins fail, and after WithoutTx its calls run under its
// own scope. A transaction that WithTenant did not open makes every join
// fail with ErrTxNotJoinable.
func ContextWithTx(ctx context.Context, tx pgx.Tx) context.Context {
	if t, ok := tx.(*tenantTx); ok && t != nil {
		if _, scoped := TenantScopeFromContext(ctx); !scoped {
			scope := t.scope
			ctx = ContextWithTenantScope(ctx, &scope)
		}
	}
	return context.WithValue(ctx, txKey{}, tx)
}

// WithoutTx detaches ctx from its transaction: calls with the returned
// context open their own transactions. The tenant scope stays.
func WithoutTx(ctx context.Context) context.Context {
	if ctx.Value(txKey{}) == nil {
		return ctx
	}
	// An untyped nil: WithTenant sees no transaction at all.
	return context.WithValue(ctx, txKey{}, nil)
}

// WithRequestTenantTx runs fn in one transaction of the context's tenant
// scope (WithRequestTenant): the repository calls fn makes with its context
// join that transaction, which commits when fn returns nil and rolls back
// otherwise.
func WithRequestTenantTx(ctx context.Context, pool *pgxpool.Pool, orgID string, fn func(ctx context.Context) error) error {
	return WithRequestTenant(ctx, pool, orgID, func(ctx context.Context, tx pgx.Tx) error {
		return fn(ContextWithTx(ctx, tx))
	})
}

// InTx reports whether ctx carries an open transaction that WithTenant
// joins.
func InTx(ctx context.Context) bool {
	t, ok := ctx.Value(txKey{}).(*tenantTx)
	return ok && t != nil && t.state.Load() == txOpen
}

// TxFailed reports whether a statement failed in the context's transaction:
// every further statement fails, and the owner rolls back. Callers that
// tolerate a repository error check it to stop early.
func TxFailed(ctx context.Context) bool {
	t, ok := ctx.Value(txKey{}).(*tenantTx)
	return ok && t != nil && t.aborted()
}

// Savepoint runs fn under a savepoint of the context's transaction: when fn
// fails, or returns nil although one of its statements failed (ErrTxAborted),
// its writes and its AfterCommit callbacks are undone and the transaction
// stays usable (two statements). Without a context transaction fn runs as it
// is.
func Savepoint(ctx context.Context, fn func(ctx context.Context) error) error {
	t, ok := ctx.Value(txKey{}).(*tenantTx)
	if !ok || t == nil || t.state.Load() != txOpen {
		return fn(ctx)
	}
	sp, err := t.Begin(ctx)
	if err != nil {
		return fmt.Errorf("savepoint: %w", err)
	}
	t.mu.Lock()
	mark, beforeMark := len(t.after), len(t.before)
	t.mu.Unlock()
	err = fn(ctx)
	if err == nil && t.aborted() {
		// A swallowed statement error: RELEASE would fail and leave the
		// transaction aborted, ROLLBACK TO keeps it usable.
		err = ErrTxAborted
	}
	if err != nil {
		if rbErr := sp.Rollback(ctx); rbErr != nil {
			return errors.Join(err, fmt.Errorf("rollback to savepoint: %w", rbErr))
		}
		t.mu.Lock()
		t.after, t.before = t.after[:mark], t.before[:beforeMark]
		t.mu.Unlock()
		return err
	}
	if err := sp.Commit(ctx); err != nil {
		return fmt.Errorf("release savepoint: %w", err)
	}
	return nil
}

// BeforeCommit runs write in the context's transaction right before its
// commit, after everything else the transaction does; writes registered
// this way run in the order they were registered, a rollback (also of a
// savepoint around the registration) drops them, and an error of one rolls
// the transaction back. Without a context transaction write runs at once.
// Writes that take an organization-wide lock until the commit go here (the
// audit chain and the event outbox, migrations 000117 and 000120), so that
// concurrent transactions of the organization wait for each other only for
// these writes and the commit (WP-334). write must not depend on later
// changes of the values it captured.
func BeforeCommit(ctx context.Context, write func() error) error {
	t, ok := ctx.Value(txKey{}).(*tenantTx)
	if !ok || t == nil {
		return write()
	}
	t.mu.Lock()
	open := t.state.Load() == txOpen
	if open {
		t.before = append(t.before, write)
	}
	t.mu.Unlock()
	if !open {
		return ErrTxDone
	}
	return nil
}

// AfterCommit runs fn once the context's transaction has committed, with a
// context detached from it; a rollback drops fn. Without a context
// transaction fn runs at once. External work (notifications, remote
// indexes, embeddings) goes here, so a transaction never waits for it while
// it holds row or advisory locks.
func AfterCommit(ctx context.Context, fn func(ctx context.Context)) {
	t, ok := ctx.Value(txKey{}).(*tenantTx)
	if !ok || t == nil {
		fn(ctx)
		return
	}
	t.mu.Lock()
	state := t.state.Load()
	if state == txOpen {
		t.after = append(t.after, fn)
	}
	t.mu.Unlock()
	if state == txCommitted {
		fn(WithoutTx(ctx))
	}
}

// sameAs reports whether s and o set the same GUC values, i.e. the same RLS
// context.
func (s *TenantScope) sameAs(o *TenantScope) bool {
	return strings.EqualFold(s.OrgID, o.OrgID) && s.UserID == o.UserID &&
		s.Clients.gucValue() == o.Clients.gucValue() && s.Sites.gucValue() == o.Sites.gucValue() &&
		s.Teams.gucValue() == o.Teams.gucValue()
}

// joinTx runs fn in the context transaction v when scope is its scope. fn's
// error is returned as it is: only the owner commits or rolls back.
func joinTx(ctx context.Context, v any, scope *TenantScope, fn func(context.Context, pgx.Tx) error) error {
	t, ok := v.(*tenantTx)
	switch {
	case !ok || t == nil:
		return ErrTxNotJoinable
	case t.state.Load() != txOpen:
		return ErrTxDone
	case !t.scope.sameAs(scope):
		return fmt.Errorf("%w: organization %s", ErrTxScopeMismatch, scope.OrgID)
	}
	return fn(ctx, t)
}
