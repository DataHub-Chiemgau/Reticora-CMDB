// Package alarm holds the alarm instances of the monitoring (ALR-01,
// MON-04, E-196 option 2): one alarm per source (rule, probe check,
// collector, configuration, capacity, SLA) and series (CI and labels) with
// a deduplication key, its state and the append-only log of its state
// changes (alarm_transition). alert_rule stays the rule definition
// (backend/internal/monitoring); the state machine and the events alarm.*
// follow in WP-982, the REST routes in WP-983.
package alarm

import (
	"errors"
	"time"
)

// Sources of an alarm (ALR-01; Konvention 45).
const (
	SourceRule      = "rule"
	SourceCheck     = "check"
	SourceCollector = "collector"
	SourceConfig    = "config"
	SourceCapacity  = "capacity"
	SourceSLA       = "sla"
)

// SourceKinds lists the sources in the order of the CHECK constraint.
var SourceKinds = []string{SourceRule, SourceCheck, SourceCollector, SourceConfig, SourceCapacity, SourceSLA}

// States of an alarm (ALR-01; Konvention 32).
const (
	StatePending      = "pending"
	StateOpen         = "open"
	StateAcknowledged = "acknowledged"
	StateResolved     = "resolved"
)

// States lists the states of an alarm.
var States = []string{StatePending, StateOpen, StateAcknowledged, StateResolved}

// Severities of an alarm.
const (
	SeverityInfo     = "info"
	SeverityWarning  = "warning"
	SeverityCritical = "critical"
)

// Severities lists the severities, lowest first.
var Severities = []string{SeverityInfo, SeverityWarning, SeverityCritical}

// Suppression reasons (ALR-01; set by WP-1031 and the alarm work packages
// of M3.11).
const (
	SuppressedMaintenance = "maintenance"
	SuppressedSymptom     = "symptom"
	SuppressedFlapping    = "flapping"
)

// SuppressedReasons lists the suppression reasons.
var SuppressedReasons = []string{SuppressedMaintenance, SuppressedSymptom, SuppressedFlapping}

// Retention is how long resolved alarms and their transitions are kept
// (ALR-01: 400 days).
const Retention = 400 * 24 * time.Hour

// SummaryMaxLen is the longest summary an alarm takes (characters).
const SummaryMaxLen = 500

// ErrNotFound is returned when an alarm does not exist or is not visible
// in the caller's scope.
var ErrNotFound = errors.New("alarm not found")

// Alarm is one alarm instance.
type Alarm struct {
	ID             string  `json:"id"`
	OrganizationID string  `json:"organization_id"`
	ClientID       *string `json:"client_id"`
	SiteID         *string `json:"site_id"`
	CIID           *string `json:"ci_id"`

	SourceKind string            `json:"source_kind"`
	SourceID   string            `json:"source_id"`
	SeriesKey  string            `json:"series_key"`
	Labels     map[string]string `json:"labels"`
	// DedupKey is source_kind:source_id:series_key (generated by the
	// database).
	DedupKey string `json:"dedup_key"`

	Severity         string  `json:"severity"`
	State            string  `json:"state"`
	SuppressedReason *string `json:"suppressed_reason"`
	IncidentID       *string `json:"incident_id"`

	OccurrenceCount int        `json:"occurrence_count"`
	FirstSeenAt     time.Time  `json:"first_seen_at"`
	LastSeenAt      time.Time  `json:"last_seen_at"`
	OpenedAt        *time.Time `json:"opened_at"`
	AcknowledgedAt  *time.Time `json:"acknowledged_at"`
	// AcknowledgedBy is the actor id without foreign key (Konvention 16).
	AcknowledgedBy *string    `json:"acknowledged_by"`
	ResolvedAt     *time.Time `json:"resolved_at"`

	Summary   string         `json:"summary"`
	Details   map[string]any `json:"details"`
	UpdatedAt time.Time      `json:"updated_at"`
}

// DedupKey returns the deduplication key of a source and series, as the
// database generates it.
func DedupKey(sourceKind, sourceID, seriesKey string) string {
	return sourceKind + ":" + sourceID + ":" + seriesKey
}

// Transition is one entry of the append-only state log of an alarm.
type Transition struct {
	ID             string    `json:"id"`
	OrganizationID string    `json:"organization_id"`
	ClientID       *string   `json:"client_id"`
	SiteID         *string   `json:"site_id"`
	AlarmID        string    `json:"alarm_id"`
	FromState      *string   `json:"from_state"`
	ToState        string    `json:"to_state"`
	FromSeverity   *string   `json:"from_severity"`
	ToSeverity     *string   `json:"to_severity"`
	At             time.Time `json:"at"`
	// ActorID is the acting user; nil is the system.
	ActorID *string `json:"actor_id"`
	Reason  string  `json:"reason"`
	Comment *string `json:"comment"`
}

// UpsertInput raises an alarm of a source and series: a new alarm in State
// (pending or open), or a further occurrence of the alarm of the same key
// that is not resolved.
type UpsertInput struct {
	SourceKind string
	SourceID   string
	SeriesKey  string
	Labels     map[string]string
	// CIID binds the alarm to a CI; client and site then follow the CI.
	CIID *string
	// ClientID is the client of an alarm without CI (e.g. that of the
	// collector group); ignored with a CI.
	ClientID *string
	Severity string
	// State is the state of a new alarm: pending or open.
	State      string
	Summary    string
	Details    map[string]any
	ObservedAt time.Time
}

// StateUpdate is the state an alarm moves to (UpdateState).
type StateUpdate struct {
	State            string
	Severity         string
	SuppressedReason *string
	IncidentID       *string
	OpenedAt         *time.Time
	AcknowledgedAt   *time.Time
	AcknowledgedBy   *string
	ResolvedAt       *time.Time
	// Details replaces the details of the alarm when not nil (the
	// observation that opens or escalates it, WP-987); nil keeps them.
	Details map[string]any
}

// ListFilter selects alarms (List). Empty fields do not filter.
type ListFilter struct {
	States      []string
	Severities  []string
	CIID        string
	ClientID    string
	SiteID      string
	SourceKinds []string
	// SourceID selects the alarms of one source (a rule, WP-984).
	SourceID   string
	IncidentID string
	// ExcludeID leaves out one alarm (the root of an incident when its
	// symptoms are counted, WP-1036).
	ExcludeID string
	// Suppressed selects suppressed (true) or unsuppressed (false) alarms.
	Suppressed *bool
	// From and To select the alarms active in the period: first seen
	// before To and not resolved before From.
	From, To *time.Time
	// OpenedFrom and OpenedTo select the alarms opened in the period
	// (opened_at at or after OpenedFrom, before OpenedTo; REST from/to,
	// WP-983). A pending alarm was never opened and does not match.
	OpenedFrom, OpenedTo *time.Time
	// After continues the list after the alarm of a previous page.
	After *Cursor
	// Limit is the page size; 0 or less is DefaultLimit.
	Limit int
}

// DefaultLimit is the page size of List without a limit.
const DefaultLimit = 50

// Cursor is the position of an alarm in the list order: newest first on
// (opened_at, id), a pending alarm without opened_at on its first_seen_at
// (SortAt).
type Cursor struct {
	At time.Time
	ID string
}

// SortAt is the sort key of an alarm in the list: opened_at, for a pending
// alarm that has not opened yet first_seen_at (COALESCE(opened_at,
// first_seen_at) in PostgreSQL).
func (a *Alarm) SortAt() time.Time {
	if a.OpenedAt != nil {
		return *a.OpenedAt
	}
	return a.FirstSeenAt
}

// Page is one page of alarms; Next is set when more alarms follow.
type Page struct {
	Items []Alarm
	Next  *Cursor
}
